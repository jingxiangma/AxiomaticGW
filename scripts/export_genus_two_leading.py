#!/usr/bin/env python3
"""Generate a native diagnostic for the proved BP/L24 leading evaluators.

The original nineteen requests are held by their existing comparison scripts.
Additional rows explore missing primary columns. Native output is search data;
the imported Lean theorems prove evaluator equality, not matrix invertibility.
"""
import argparse
import hashlib
from pathlib import Path

from export_admcycles_certificate import require
from export_surface_l24 import CODEC_SOURCE, CODEC_SHA256
from explore_surface_bp import EXPECTED_CASES as BP_CASES
from explore_surface_l24 import EXPECTED_CASES as L24_CASES

EXTRA_CASES = {
    "p2_line_HHP": (0, (1,), 1, (1, 1, 2)),
    "p2_line_HPP": (0, (1,), 0, (1, 2, 2)),
    "f1_F_HHP": (1, (0, 1), 0, (1, 1, 2)),
    "f1_F_EHP": (1, (0, 1), 0, (3, 1, 2)),
    "bl2_E1E2_HHP": (2, (1, 1, 0), 0, (1, 1, 2)),
    "bl2_E1E2_E1E2P": (2, (1, 1, 0), 0, (3, 4, 2)),
}

BODY = r'''
/-- Every canonical primary/first-descendant column, including absent variables. -/
def canonicalColumns (X : SurfaceTarget) (beta : X.Curve) : List (SurfaceQuery X) :=
  let e := X.effective.energy beta
  let divisors : List (SurfaceBasisLabel X) :=
    .hyperplane :: (List.finRange X.blowups).map .exceptional
  SurfaceQuery.points X 2 beta (e + 1) ::
    divisors.map (fun b ↦ SurfaceFirstDescendant.query 2 beta b e) ++
    if e = 0 then [] else [SurfaceFirstDescendant.query 2 beta .point (e - 1)]

def columnJSON {X : SurfaceTarget} (q : SurfaceQuery X) : Json :=
  Json.mkObj [("genus", toJson q.genus),
    ("curve", toJson ((List.finRange (X.blowups + 1)).map q.beta)),
    ("insertions", toJson ((q.insertions.map fun i ↦
      [labelCode i.label, i.psi]).mergeSort (· ≤ ·)))]

def caseJSON (family name : String) (X : SurfaceTarget) (beta : X.Curve) (n : ℕ)
    {m : ℕ} (a : Fin m → SurfaceBasisLabel X)
    (entry : SurfacePolynomialReduction.Variable X → ℚ) : Json :=
  let columns := canonicalColumns X beta
  Json.mkObj [("family", toJson family), ("name", toJson name),
    ("blowups", toJson X.blowups),
    ("curve", toJson ((List.finRange (X.blowups + 1)).map beta)),
    ("additional_markings", toJson n),
    ("labels", toJson ((List.finRange m).map (fun i ↦ labelCode (a i)))),
    ("columns", toJson (columns.map columnJSON)),
    ("coefficients", toJson (columns.map fun q ↦ ratJSON (entry (.inr q))))]

def bpCase (name : String) (X : SurfaceTarget) (beta : X.Curve) (n : ℕ)
    (a : Fin 3 → SurfaceBasisLabel X) : Json :=
  caseJSON "BP" name X beta n a
    (BelorousskiPandharipande.leadingCoefficient X n beta 0 (SurfaceGenusZero.pointLabels a n))

def l24Case (name : String) (X : SurfaceTarget) (beta : X.Curve) (n : ℕ)
    (a : Fin 4 → SurfaceBasisLabel X) : Json :=
  caseJSON "L24" name X beta n a
    (L24Relation.leadingCoefficient X n beta 0 (SurfaceGenusZero.pointLabels a n))

end AxiomaticGW.GenusTwoLeadingExport
open AxiomaticGW GenusTwoLeadingExport Lean

def main (args : List String) : IO Unit := do
  let jobs : List (String × (Unit → Json)) := [
__JOBS__]
  let stderr ← IO.getStderr
  let mut cases := []
  for (name, run) in jobs do
    if args.isEmpty || args.contains name then
      stderr.putStrLn s!"Leading matrix: {name}"
      cases := cases ++ [run ()]
  IO.println (Json.mkObj [("schema_version", toJson (1 : ℕ)),
    ("cases", toJson cases)]).compress
'''


def label(b):
    return [".unit", ".hyperplane", ".point"][b] if b < 3 else f".exceptional {b - 3}"


def generate():
    raw = CODEC_SOURCE.read_bytes()
    require(hashlib.sha256(raw).hexdigest() == CODEC_SHA256, "Changed held query codecs")
    text = raw.decode()
    start, end = "namespace AxiomaticGW.SurfaceBPExport\n", "/-- Export both stages"
    require(text.count(start) == text.count(end) == 1, "Ambiguous codec boundaries")
    helpers = text.split(start, 1)[1].split(end, 1)[0]
    jobs = []
    for family, cases in (("BP", BP_CASES), ("L24", L24_CASES), ("BP", EXTRA_CASES)):
        for name, (r, beta, n, labels) in cases.items():
            target = [".plane", ".hirzebruchOne", ".blowupTwo"][r]
            curve = "![" + ",".join(map(str, beta)) + "]"
            states = "![" + ", ".join(label(b) for b in labels) + "]"
            function = "bpCase" if family == "BP" else "l24Case"
            jobs.append(f'    ("{name}", fun _ ↦\n'
                        f'      {function} "{name}" {target} {curve} {n}\n'
                        f'        {states})')
    return (
        "/-\nCopyright (c) 2026 JMA. All rights reserved.\n"
        "Released under Apache 2.0 license as described in the file LICENSE.\nAuthors: JMA\n-/\n"
        "module\n\npublic import AxiomaticGW.Surfaces.GenusTwoLeadingTerms\n\n"
        "/-!\n# Native leading-coefficient diagnostic\n\n"
        "Generated by `scripts/export_genus_two_leading.py`. Native values are search data.\n-/\n\n"
        "@[expose] public section\nset_option maxRecDepth 20000\n\n"
        "namespace AxiomaticGW.GenusTwoLeadingExport\n" + helpers + "\n" +
        BODY.replace("__JOBS__", ",\n".join(jobs))
    )


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    source = generate()
    if args.check:
        require(args.output.read_text() == source, "Stored diagnostic program differs")
    else:
        args.output.write_text(source)


if __name__ == "__main__":
    main()
