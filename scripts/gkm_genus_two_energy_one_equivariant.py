#!/usr/bin/env python3
"""Replay the full bivariate fractions of the fixed genus-two energy-one frame."""
import hashlib

from export_admcycles_certificate import rational
from export_gkm_certificate import has_variable_denominator, key
from gkm_genus_two_energy_one import KIND, REQUESTS
from gkm_regular_fraction_table import fraction_table, indexed_array
from gkm_report_cli import report_cli
from gkm_three_point_descendants import read_report


def emit(raw):
    _, grouped = read_report(raw, requests=REQUESTS, genus=2, kind=KIND)
    fractions = []
    seen = {}
    indices = {}
    for target in ("X1", "X2"):
        indexed = {(tuple(c["class"]), tuple(c["powers"]), tuple(c["labels"])): c
                   for c in grouped[target]}
        indices[target] = []
        for request in REQUESTS[target]:
            case = indexed[request]
            fraction = case["equivariant"]
            literal = key(fraction)
            if literal not in seen:
                seen[literal] = len(fractions)
                fractions.append((fraction, rational(case["ordinary"])))
            indices[target].append(str(seen[literal]))

    count = len(fractions)
    variable_denominator = any(has_variable_denominator(f) for f, _ in fractions)
    lines = ["module", "",
             "public import AxiomaticGW.GKM.EquivariantCoefficients",
             "public import AxiomaticGW.GKM.Fixtures.GenusTwoEnergyOneClaims",
             "public import Mathlib.Tactic.FinCases", "public import Mathlib.Tactic.NormNum",
             *(["public import Mathlib.Tactic.Ring"] if variable_denominator else []), "",
             "/-! # Equivariant localization fractions for every genus-two energy-one request",
             "", "Generated by `scripts/gkm_genus_two_energy_one_equivariant.py`.",
             "Report SHA256: " + hashlib.sha256(raw).hexdigest(), "",
             "Each index refers to the ordered request of the ordinary frame. Repeated literal",
             "fractions share a table entry. Lean checks the complete expression in the",
             "fraction field and checks regular specialization on its reported representative.",
             "-/", "", "@[expose] public section", "",
             "namespace AxiomaticGW.GKM.GenusTwoEnergyOne", "", "open EquivariantCoefficients",
             ""]
    lines += fraction_table(fractions)
    for target, ns in (("X1", "OneBlowup"), ("X2", "TwoBlowups")):
        size = len(indices[target])
        lines += [f"namespace {ns}", "",
                  "/-- Dictionary entry for this ordered curve and insertion request. -/",
                  f"def fractionIndex (i : Fin {size}) : Fin {count} :=",
                  indexed_array(indices[target], f"Fin {count}", 20), "",
                  "/-- The complete equivariant localization sum for the indexed request. -/",
                  f"noncomputable def equivariant (i : Fin {size}) : Coefficient :=",
                  "  FractionTable.fraction (fractionIndex i)", "",
                  f"private theorem constants_eq_values : ∀ i : Fin {size},",
                  "    FractionTable.constants (fractionIndex i) = values i := by decide +kernel", "",
                  "/-- The reported expression agrees with the ordinary value throughout the field. -/",
                  f"theorem equivariant_eq_ordinary (i : Fin {size}) :",
                  "    equivariant i = (values i : Coefficient) := by",
                  "  rw [← constants_eq_values i]",
                  "  exact FractionTable.fraction_eq_constant (fractionIndex i)", "",
                  "/-- The reported expression specializes regularly at the same row index. -/",
                  f"theorem specializes (i : Fin {size}) : Specializes (equivariant i) (values i) := by",
                  "  rw [← constants_eq_values i]",
                  "  exact FractionTable.specializes (fractionIndex i)", "", f"end {ns}", ""]
    return "\n".join(lines + ["end AxiomaticGW.GKM.GenusTwoEnergyOne", ""])


if __name__ == "__main__":
    report_cli(__doc__, requests=REQUESTS, genus=2, kind=KIND, emit=emit)
