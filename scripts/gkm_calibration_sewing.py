#!/usr/bin/env python3
"""Read the archived two-point localization matrices at sums of two primitive classes."""
import argparse
import hashlib
import json
from pathlib import Path

from check_gkm_inputs import polynomial, require
from export_gkm_first_calibration import INPUT, read_report as read_first
from gkm_calibration_recursion import read_report
from gkm_equivariant_calibration import stack, table

ROOT = Path(__file__).resolve().parents[1]
REPORT = ROOT / "environments/gkm-higher-calibration-comparison.json"
OUTPUT = ROOT / "AxiomaticGW/GKM/Fixtures/CalibrationSewingData.lean"
# A full class and inverse-loop power. Both exceptional labels keep their native order.
CASES = {
    "X0": [((2,), 4)],
    "X1": [(b, n) for b in ((1, 1), (2, 0)) for n in (2, 3)],
    "X2": [(b, n) for b in ((0, 1, 1), (1, 0, 1), (2, 0, 0), (0, 2, 0)) for n in (2, 3)],
}


def expression(f):
    require(f["denominator"] == [[[0, 0], [1, 1]]], "Expected a polynomial")
    terms = []
    for (a, b), q in polynomial(f["numerator"]).items():
        factors = ([str(q.numerator)] if q.denominator == 1 else [f"({q.numerator}/{q.denominator})"])
        for symbol, degree in (("u", a), ("v", b)):
            if degree:
                factors.append(symbol if degree == 1 else f"{symbol}^{degree}")
        terms.append("*".join(factors))
    return "+".join(terms).replace("+-", "-") or "0"


def emit(raw):
    _, grouped = read_report(raw)
    first_path = ROOT / "environments/gkm-first-calibration-comparison.json"
    first_raw = first_path.read_bytes()
    _, first = read_first(first_raw)
    frames = {f["target"]: f for f in json.loads(INPUT.read_bytes())["targets"]}
    lines = ["/-", "Copyright (c) 2026 JMA. All rights reserved.",
             "Released under Apache 2.0 license as described in the file LICENSE.", "Authors: JMA", "-/",
             "module", "", "public import AxiomaticGW.Coefficients.RationalTerms",
             "public import Mathlib.LinearAlgebra.Matrix.Notation", "",
             "/-! # Nonprimitive equivariant two-point coefficients",
             "", "Generated by `scripts/gkm_calibration_sewing.py` from the native first and higher calibration",
             "archives. Basis rows carry the attaching node and columns the retained marking.",
             "", f"Higher calibration SHA-256: `{hashlib.sha256(raw).hexdigest()}`.",
             f"First calibration SHA-256: `{hashlib.sha256(first_raw).hexdigest()}`.", "-/", "",
             "@[expose] public section", "namespace AxiomaticGW.GKM.CalibrationSewingData",
             "open Matrix", "variable {R : Type*} [Field R]"]
    for target, section in (("X0", "Plane"), ("X1", "OneBlowup"), ("X2", "TwoBlowups")):
        cases = CASES[target]
        records = {(tuple(r["class"]), r["inverse_loop_power"]): r for r in grouped[target]}
        rank = len(frames[target]["basis"])
        requests = []
        for key in cases:
            source = records[key]
            beta = ", ".join(map(str, source["class"]))
            requests.append(f"(![{beta}], {source['inverse_loop_power']})")
        lines.extend(["", f"namespace {section}", "",
                      "/-- Full effective class and inverse-loop power stored in the native report. -/",
                      f"def request : Fin {len(cases)} → (Fin {rank - 2} → ℕ) × ℕ :=",
                      "  " + stack(requests, 4), ""])
        pool = {}
        coeffs = []
        def index(f):
            require(f["denominator"] == [[[0, 0], [1, 1]]], "Expected a polynomial")
            key = tuple(polynomial(f["numerator"]).items())
            if key not in pool:
                pool[key] = len(pool)
                coeffs.append(f)
            return str(pool[key])
        def table_indices(matrix):
            return table([[index(q) for q in mrow] for mrow in matrix], 8)
        inverse = table_indices(frames[target]["inverse_metric"])
        boundary = stack([table_indices(records[c]["paired_equivariant"]) for c in cases], 6)
        incoming = {(r["inverse_loop_power"], tuple(r["class"])): r for r in first[target] + grouped[target]}
        def primitive(psi, d):
            beta = tuple(int(i == d) for i in range(rank - 2))
            return table_indices(incoming[psi + 1, beta]["paired_equivariant"])
        primitives = stack([stack([primitive(k, d) for d in range(rank - 2)], 6) for k in range(3)], 4)
        def multiset(elements):
            return "{" + ", ".join(elements) + "}" if elements else "0"
        def monomials(f):
            pieces = []
            for (a, b), q in polynomial(f["numerator"]).items():
                powers = multiset(["0"] * a + ["1"] * b)
                pieces.append(f"({q}, {powers})")
            return multiset(pieces)
        bound = len(pool)
        def dictionary(items):
            return "\n".join([f"  | {i} => {item}" for i, item in enumerate(items)] + ["  | _ => 0"])
        lines.extend(["/-- Number of distinct polynomials in this native dictionary. -/",
                      f"def dictionarySize : ℕ := {bound}", "",
                      "/-- Rational monomials of the native polynomial dictionary. -/",
                      f"def terms : Fin {bound} → RationalTerms (Fin 2)",
                      dictionary([monomials(f) for f in coeffs]), "",
                      "/-- Native dictionary entries as arithmetic expressions. -/",
                      f"def value (u v : R) : Fin {bound} → R",
                      dictionary([expression(f) for f in coeffs]), "",
                      "/-- Dictionary indices of the inverse metric. -/",
                      f"def metricIndex : Matrix (Fin {rank}) (Fin {rank}) (Fin {bound}) :=",
                      "  " + inverse, "", "/-- Dictionary indices of the composite endpoints. -/",
                      f"def endpointIndex : Fin {len(cases)} → Matrix (Fin {rank}) (Fin {rank}) (Fin {bound}) :=",
                      "  " + boundary, "", "/-- Dictionary indices of the native primitive descendants. -/",
                      f"def primitiveIndex : Fin 3 → Fin {rank - 2} → Matrix (Fin {rank}) (Fin {rank}) (Fin {bound}) :=",
                      "  " + primitives, "",
                      "/-- Inverse equivariant metric in the native toric basis. -/",
                      f"def inverseMetric (u v : R) : Matrix (Fin {rank}) (Fin {rank}) R :=",
                      "  fun i j ↦ value u v (metricIndex i j)", "",
                      "/-- Native paired coefficient at the specified full class and power. -/",
                      f"def paired (u v : R) : Fin {len(cases)} → Matrix (Fin {rank}) (Fin {rank}) R :=",
                      "  fun r i j ↦ value u v (endpointIndex r i j)", "", f"end {section}"])
    return "\n".join(lines + ["", "end AxiomaticGW.GKM.CalibrationSewingData", ""])


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--report", type=Path, default=REPORT)
    parser.add_argument("--output", type=Path, default=OUTPUT)
    parser.add_argument("--check", action="store_true")
    opts = parser.parse_args()
    source = emit(opts.report.read_bytes())
    if opts.check:
        require(opts.output.read_text() == source, "Native calibration sewing entries changed")
    else:
        opts.output.write_text(source)
