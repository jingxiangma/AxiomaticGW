#!/usr/bin/env python3
"""Extract the primitive-class paired calibration coefficients from the pinned reports."""
import argparse
import json
from pathlib import Path

import check_gkm_inputs as codec
from export_gkm_first_calibration import INPUT, TARGETS, read_report as read_first
from gkm_calibration_recursion import read_report as read_higher
from gkm_small_quantum_generators import polynomial


ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "AxiomaticGW/GKM/Fixtures/EquivariantCalibrationData.lean"


def stack(items, indent):
    return "![" + (",\n" + " " * indent).join(items) + "]"


def table(rows, indent):
    return stack(["![" + ", ".join(row) + "]" for row in rows], indent)


def emit():
    _, first = read_first((ROOT / "environments/gkm-first-calibration-comparison.json").read_bytes())
    _, higher = read_higher((ROOT / "environments/gkm-higher-calibration-comparison.json").read_bytes())
    frames = {s["target"]: s for s in json.loads(INPUT.read_bytes())["targets"]}
    lines = ["/-", "Copyright (c) 2026 JMA. All rights reserved.",
             "Released under Apache 2.0 license as described in the file LICENSE.", "Authors: JMA", "-/",
             "module", "", "public import Mathlib.LinearAlgebra.Matrix.Notation", "",
             "/-! # Incoming equivariant two-point coefficients for full primitive curve classes",
             "", "Generated by `scripts/gkm_equivariant_calibration.py`. Arrays are ordered by the",
             "retained marking's cotangent exponent 0, 1, 2 (inverse-loop powers 1, 2, 3), then",
             "by full effective-class generator. The first state index is the attaching node.", "-/", "",
             "@[expose] public section", "namespace AxiomaticGW.GKM.EquivariantCalibrationData",
             "open Matrix", "variable {R : Type*} [CommRing R]"]
    for target, namespace, _ in TARGETS:
        frame = frames[target]
        rank = len(frame["basis"])
        cases = {(c["tail_psi_power"], tuple(c["class"])): c for c in first[target] + higher[target]}
        pool = {}
        def encode(raw):
            value = polynomial(raw)
            if value in {"0", "(1 : R)", "(-1 : R)"}:
                return {"0": "0", "(1 : R)": "1", "(-1 : R)": "-1"}[value]
            if value not in pool:
                pool[value] = len(pool)
            return f"poly u v {pool[value]}"
        c1 = "![" + ", ".join(map(encode, frame["c1_coordinates"])) + "]"
        degrees = "![" + ", ".join(map(str, frame["energy_weights"])) + "]"
        polynomials = [codec.polynomial(q["numerator"]) for q in frame["c1_coordinates"]]
        def cup_entry(i,j):
            accum = {}
            for h, factor in enumerate(polynomials):
                value = frame["products"][h][j][i]
                codec.require(value["denominator"] == [[[0,0],[1,1]]], "Nonpolynomial classical product")
                accum = codec.add_polynomials(accum, codec.multiply_polynomials(
                    factor, codec.polynomial(value["numerator"])))
            return encode({"numerator":[[list(v), [c.numerator,c.denominator]] for v,c in sorted(accum.items())],
                           "denominator":[[[0,0],[1,1]]]})
        cup = table([[cup_entry(i,j) for j in range(rank)] for i in range(rank)], 4)
        values = []
        for psi in range(3):
            values.append(stack([table([[encode(q) for q in row] for row in
                cases[psi,tuple(int(r==d) for r in range(rank-2))]["paired_equivariant"]], 8)
                for d in range(rank-2)], 6))
        lines += ["", f"namespace {namespace}", "",
                  f"def poly (u v : R) : Fin {len(pool)} → R"]
        lines += [f"  | {i if i + 1 < len(pool) else '_'} => {value}"
                  for value, i in pool.items()]
        lines += ["", f"def c1 (u v : R) : Fin {rank} → R := {c1}",
                  "",f"def energy : Fin {rank-2} → ℕ := {degrees}",
                  "", f"def cup (u v : R) : Matrix (Fin {rank}) (Fin {rank}) R :=", "  "+cup,
                  "", f"def paired (u v : R) : Fin 3 → Fin {rank-2} → Matrix (Fin {rank}) (Fin {rank}) R :=",
                  "  "+stack(values,4), "", f"end {namespace}"]
    return "\n".join(lines + ["", "end AxiomaticGW.GKM.EquivariantCalibrationData", ""])


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, default=OUTPUT)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    content = emit()
    if args.check:
        codec.require(args.output.read_text() == content, "Changed equivariant calibration replay")
    else:
        args.output.write_text(content)
