#!/usr/bin/env python3
"""Emit Lean replay for fixed GKM fan, full curve, and invariant-edge conventions.

The Python input check is preflight only. Fixed Lean requests bind the emitted
candidate proofs, including all exact localization intersection identities.
This does not certify stable-map localization, graph stabilization, CohFT
classes, or numerical GW values.
"""

import argparse
import hashlib
import json
from pathlib import Path
import sys

import check_gkm_inputs as codec
from export_gkm_certificate import vector, matrix, simp_text, VECTOR_SIMP, BASIC_SIMP


FRAMES = [('X0', 'Plane', 'plane', 3),
          ('X1', 'OneBlowup', 'hirzebruchOne', 4),
          ('X2', 'TwoBlowups', 'blowupTwo', 5)]


def integer_vector(values):
    if isinstance(values, list):
        return vector([integer_vector(value) for value in values])
    return str(codec.integer(values))


def fin_text(value, bound):
    value = codec.integer(value)
    codec.require(0 <= value < bound, 'Finite label outside its declared range')
    return f'⟨{value}, by decide⟩'


def wall_classes(frame):
    result = [None] * len(frame['rays'])
    for edge in frame['edges']:
        codec.require(len(edge['wall']) == 1, 'Expected a surface invariant wall')
        rho = codec.integer(edge['wall'][0])
        codec.require(0 <= rho < len(result) and result[rho] is None,
                      'Repeated or invalid wall')
        result[rho] = edge['class']
    codec.require(all(value is not None for value in result), 'Missing invariant wall')
    return result


def emit(report, targets=None):
    codec.check_report(report)
    lines = ['/-', 'Copyright (c) 2026 JMA. All rights reserved.',
             'Released under Apache 2.0 license as described in the file LICENSE.',
             'Authors: JMA', '-/', 'module', '',
             'public import AxiomaticGW.GKM.Fixtures.CurveFrames',
             'public import Mathlib.Tactic.FinCases',
             'public import Mathlib.Tactic.FieldSimp',
             'public import Mathlib.Tactic.NormNum',
             'public import Mathlib.Tactic.Ring', '',
             '/-!', '# Kernel replay of full GKM curve and invariant-edge conventions', '',
             'Generated by scripts/export_gkm_curve_certificate.py from exact candidate data.',
             'The fan requests and surface coordinate semantics are independently fixed.',
             'Closed finite checks use kernel-checked decide; symbolic identities use field arithmetic.',
             'No geometric localization, CohFT class, or numerical GW invariant is claimed.', '-/', '',
             '@[expose] public section', '', 'namespace AxiomaticGW.GKM.CurveReplay', '',
             'open CurveConventionCertificate EquivariantCoefficients', 'open Matrix', '',
             'noncomputable section']
    for frame, (target, name, surface, n) in zip(report['targets'], FRAMES):
        codec.require(frame['target'] == target, 'Changed fixed target order')
        if targets is not None and target not in targets:
            continue
        intersections = [[codec.rational(value) for value in row]
                         for row in frame['divisor_curve_intersections']]
        codec.require(all(value.denominator == 1 for row in intersections for value in row),
                      'Nonintegral divisor intersection')
        fields = {
            'rays': integer_vector(frame['rays']),
            'points': vector([vector([fin_text(rho, n) for rho in point])
                              for point in frame['points']]),
            'tangent': integer_vector(frame['tangent_characters']),
            'curveMatrix': matrix([[str(codec.integer(value)) for value in row]
                                   for row in frame['curve_to_signed_lattice']]),
            'weights': integer_vector(frame['energy_weights']),
            'wallClasses': integer_vector(wall_classes(frame)),
            'intersections': integer_vector([[value.numerator for value in row]
                                             for row in intersections]),
        }
        edges = []
        for edge in frame['edges']:
            u, v, degree = edge['normal_bundles'][0]
            parts = ['source := ' + fin_text(edge['source'], n),
                     'target := ' + fin_text(edge['target'], n),
                     'wall := ' + fin_text(edge['wall'][0], n),
                     'weight := ' + integer_vector(edge['weight']),
                     'curve := ' + integer_vector(edge['class']),
                     'normalSource := ' + fin_text(u, n),
                     'normalTarget := ' + fin_text(v, n),
                     'normalDegree := ' + str(codec.integer(degree))]
            edges.append('{ ' + ',\n      '.join(parts) + ' }')
        fields['edges'] = vector(edges)
        lines += ['', f'namespace {name}', '',
                  '/-- Serialized fan, full lattice, wall, and oriented edge data. -/',
                  f'def tables : Tables .{surface} {n} {n} where']
        lines += [f'  {field} := {value}' for field, value in fields.items()]
        lines += ['', 'set_option maxHeartbeats 2000000 in',
                  '-- Replay checks finite fan adjacency and every symbolic divisor intersection.',
                  '/-- Kernel acceptance against the independently held fan and surface API. -/',
                  f'theorem accepted : Accepts CurveFrames.{name}.request tables where']
        for field in ['rays_eq', 'points_eq', 'tangent_eq', 'matrix_eq', 'weights_eq', 'walls_eq',
                      'generators_eq', 'tangent_dual']:
            lines += [f'  {field} := by decide']
        simplify = ['tables', f'CurveFrames.{name}.request', f'SurfaceFrames.{name}.request',
                    'divisorRestriction', 'character', 'Fin.sum_univ_succ', 'Fintype.sum_empty']
        finite_simp = VECTOR_SIMP + ['Fin.coe_ofNat_eq_mod', 'Fin.val_ofNat'] + BASIC_SIMP
        simplify += finite_simp
        for field in ['state_euler', 'state_tangentSum']:
            lines += [f'  {field} := by', '    intro p', '    fin_cases p',
                      '    all_goals dsimp only [' + simp_text([f'CurveFrames.{name}.request',
                        f'SurfaceFrames.{name}.request', 'character', 'Matrix.cons_val']) + ']',
                      '    all_goals norm_num only [' + simp_text(finite_simp) + ']',
                      '    all_goals ring']
        lines += ['  intersections_eq := by decide']
        lines += ['  intersections_trace := by', '    intro i rho', '    fin_cases i',
                  '    all_goals fin_cases rho',
                  '    all_goals dsimp only [' + simp_text(['tables', f'CurveFrames.{name}.request',
                    f'SurfaceFrames.{name}.request', 'divisorRestriction', 'character', 'Matrix.cons_val']) + ']',
                  '    all_goals norm_num only [' + simp_text(simplify) + ']']
        if n > 3:
            lines += ['    all_goals try dsimp only [Matrix.cons_val]']
        lines += ['    all_goals field_simp [x_ne_zero, y_ne_zero, x_sub_y_ne_zero, y_sub_x_ne_zero]',
                  '    all_goals ring']
        for field in ['walls_bijective', 'edge_endpoints', 'edges_complete', 'edge_classes',
                      'source_weights', 'target_weights', 'normal_branches', 'normal_energy',
                      'normal_characters']:
            if field in ['edge_endpoints', 'edges_complete', 'normal_branches']:
                definitions = 'Incident' if field == 'edge_endpoints' else 'Adjacent, Incident'
                lines += [f'  {field} := by', f'    simp only [{definitions}]', '    decide']
            else:
                lines += [f'  {field} := by decide']
        lines += ['', f'end {name}']
    lines += ['', 'end', '', 'end AxiomaticGW.GKM.CurveReplay', '']
    return '\n'.join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('report', type=Path)
    parser.add_argument('--output', type=Path, required=True)
    parser.add_argument('--target', action='append', choices=['X0', 'X1', 'X2'])
    args = parser.parse_args()
    report = json.loads(args.report.read_text(), object_pairs_hook=codec.unique_object)
    proof = emit(report, args.target)
    args.output.write_text(proof)
    print(json.dumps({'status': 'emitted_candidate_proof',
                      'scope': 'fixed fan, full curve and invariant-edge conventions; no GW values',
                      'targets': args.target or ['X0', 'X1', 'X2'],
                      'input_sha256': hashlib.sha256(args.report.read_bytes()).hexdigest(),
                      'proof_bytes': len(proof.encode()),
                      'proof_sha256': hashlib.sha256(proof.encode()).hexdigest()}, sort_keys=True))


if __name__ == '__main__':
    try:
        main()
    except (ValueError, TypeError, KeyError, IndexError, OSError) as error:
        print(f'GKM curve certificate export FAILED: {error}', file=sys.stderr)
        raise SystemExit(1)
