#!/usr/bin/env python3
"""Exchange the small-quantum three-point tensors of the six primitive generator classes."""
import itertools
from fractions import Fraction

from gkm_report_cli import report_cli
from gkm_three_point_descendants import read_report
from export_gkm_inputs import require

KIND = "gkm_localization.small_quantum_generators"
BASIS = {"X0": ["unit", "H", "pt"], "X1": ["unit", "H", "E1", "pt"],
         "X2": ["unit", "H", "E1", "E2", "pt"]}
REQUESTS = {target: [(tuple(int(j == i) for j in range(rank)), (0, 0, 0), labels)
                     for i in range(rank)
                     for labels in itertools.combinations_with_replacement(basis, 3)]
            for rank, (target, basis) in enumerate(BASIS.items(), 1)}


def polynomial(function):
    require(function["denominator"] == [[[0, 0], [1, 1]]], "Expected collected polynomial")
    terms = []
    for (i, j), (n, d) in function["numerator"]:
        q = Fraction(n, d)
        require(q.denominator == 1, "Expected integral polynomial coefficients in the toric frame")
        factors = [f"({q.numerator} : R)"]
        factors.extend(symbol if power == 1 else f"{symbol}^{power}"
                       for symbol, power in (("u", i), ("v", j)) if power)
        terms.append(" * ".join(factors))
    return " + ".join(terms) or "0"


def emit(raw):
    _, grouped = read_report(raw, requests=REQUESTS, genus=0, kind=KIND)
    lines = ["/-", "Copyright (c) 2026 JMA. All rights reserved.",
             "Released under Apache 2.0 license as described in the file LICENSE.", "Authors: JMA",
             "-/", "module", "", "public import Mathlib.Algebra.Ring.Defs",
             "", "/-!", "# Native three-point coefficients of primitive generator classes", "",
             "Generated by `scripts/gkm_small_quantum_generators.py`. Entries follow the sorted",
             "three-state multiset and the full effective generator index. Zero entries are retained",
             "in the source report and checked during exhaustive decoding.", "-/", "",
             "@[expose] public section", "namespace AxiomaticGW.GKM.SmallQuantumGeneratorData",
             "variable {R : Type*} [CommRing R]"]
    for size, (target, name) in enumerate((("X0", "plane"), ("X1", "one"), ("X2", "two")), 3):
        basis = BASIS[target]
        lines += ["", "/-- Coefficients in the labeled ordinary surface frame with its toric lifts. -/",
                  f"def {name} ({'u v' if name != 'two' else '_u _v'} : R) : Fin {size-2} → Fin {size} → Fin {size} → Fin {size} → R"]
        for case in grouped[target]:
            value = polynomial(case["equivariant"])
            if value != "0":
                states = [basis.index(a) for a in case["labels"]]
                for a, b, c in sorted(set(itertools.permutations(states))):
                    lines.append(f'  | {case["class"].index(1)}, {a}, {b}, {c} => {value}')
        lines.append("  | _, _, _, _ => 0")
    return "\n".join(lines + ["", "end AxiomaticGW.GKM.SmallQuantumGeneratorData", ""])


if __name__ == "__main__":
    report_cli(__doc__, requests=REQUESTS, genus=0, kind=KIND, emit=emit)
