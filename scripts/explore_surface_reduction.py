#!/usr/bin/env python3
"""Reduce the frozen surface Getzler polynomials using exact Sage arithmetic.

The rules are dimension vanishing and positive-class primary string/divisor
reduction. Degree-zero ancestors and nonzero powers remain explicit variables.
An optional Lean file checks every distinct component substitution in the
kernel. These checks do not certify the independent raw graph expansion or
supply any geometric GW input.
"""

import argparse
from collections import Counter
import gzip
import hashlib
import importlib.metadata
import json
import os
from pathlib import Path
import platform
import tempfile


ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "environments/surface-getzler-exploration.json"
SOURCE_SHA256 = "2487976e3c3e23dafa898a045bf0c4c68fcd891d9ca63dd160c5c958de7cc3a6"
TARGETS = {"P2": ("plane", (3,)), "F1": ("hirzebruchOne", (1, 2)),
           "Bl2P2": ("blowupTwo", (1, 1, 1))}


def digest(data):
    return hashlib.sha256(data).hexdigest()


def tuple_key(raw):
    genus, curve, insertions = raw
    return (genus, tuple(curve), tuple(tuple(s) for s in insertions))


def reduce_key(target, key, QQ):
    genus, curve, insertions = key
    _, weights = TARGETS[target]
    if len(curve) != len(weights) or any(b < 0 for b in curve):
        raise ValueError("Invalid full curve coordinates")
    if 2 * genus + len(insertions) < 3:
        raise ValueError("An input ancestor component is unstable")
    if any(label < 0 or label > len(weights) + 1 or psi < 0 for label, psi in insertions):
        raise ValueError("Invalid insertion")
    codimension = sum(({0: 0, 1: 1, 2: 2}.get(label, 1)) + psi
                      for label, psi in insertions)
    energy = sum(w * b for w, b in zip(weights, curve))
    if codimension != energy + genus - 1 + len(insertions):
        return None, "dimension_zero"
    if not any(curve) or any(psi for _, psi in insertions):
        return (QQ(1), ("ancestor", *key)), "retained_ancestor"
    coefficient = QQ(1)
    for label, _ in insertions:
        if label == 0:
            coefficient = QQ(0)
        elif label == 1:
            coefficient *= curve[-1]
        elif label >= 3:
            coefficient *= curve[-1] - curve[label - 3]
    if not coefficient:
        return None, "primary_zero"
    points = sum(label == 2 for label, _ in insertions)
    return (coefficient, ("query", genus, curve, ((2, 0),) * points)), "primary_points"


def lean_vector(curve):
    return "![" + ", ".join(map(str, curve)) + "]"


def lean_replay(checks):
    lines = ["-- Generated by scripts/explore_surface_reduction.py.",
             "-- Component substitutions only; geometric inputs remain explicit.",
             "import AxiomaticGW.Surfaces.PolynomialReduction", "",
             "open AxiomaticGW SurfacePolynomialReduction", ""]
    for (target, key), result in sorted(checks.items()):
        lean_target = "." + TARGETS[target][0]
        genus, curve, insertions = key
        labels = [".unit", ".hyperplane", ".point"]
        entries = ", ".join(
            f"⟨{labels[label] if label < 3 else f'.exceptional {label - 3}'}, {psi}⟩"
            for label, psi in insertions)
        query = (f"⟨{genus}, {lean_vector(curve)}, "
                 f"(↑([{entries}] : List (SurfaceInsertion {lean_target})) : "
                 f"Multiset (SurfaceInsertion {lean_target})), by decide +kernel⟩")
        if result is None:
            expected = "none"
        else:
            coefficient, residual = result
            numerator, denominator = coefficient.numerator(), coefficient.denominator()
            value = (".inl q" if residual[0] == "ancestor" else
                     f".inr (SurfaceQuery.points {lean_target} {genus} "
                     f"{lean_vector(curve)} {len(residual[3])})")
            expected = f"some (({numerator} / {denominator} : ℚ), {value})"
        lines.append(f"example : (let q : SurfaceAncestorKey {lean_target} := {query};\n"
                     f"    reduceVariable q = {expected}) := by decide +kernel\n")
    return "\n".join(lines)


def explore(replay_path=None):
    from sage.all import QQ
    from sage.version import version

    if version != "10.9" or importlib.metadata.version("admcycles") != "1.4":
        raise RuntimeError("Review the pinned Sage/admcycles environment")
    source_data = SOURCE.read_bytes()
    if digest(source_data) != SOURCE_SHA256:
        raise RuntimeError("The frozen polynomial report changed")
    source = json.loads(source_data)
    cases, checks = [], {}
    for case in source["cases"]:
        target = case["target"]
        compressed = (ROOT / case["polynomial_file"]).read_bytes()
        if digest(compressed) != case["compressed_sha256"]:
            raise RuntimeError("Compressed input hash mismatch")
        payload = gzip.decompress(compressed)
        if digest(payload) != case["polynomial_sha256"]:
            raise RuntimeError("Sparse polynomial hash mismatch")
        terms = [(tuple(tuple_key(q) for q in monomial), QQ(c[0]) / c[1])
                 for monomial, c in json.loads(payload)]
        keys = {q for monomial, _ in terms for q in monomial}
        if len(keys) != case["distinct_component_variables"] or len(terms) != case["collected_monomials"]:
            raise RuntimeError("Input counts changed")
        reductions = {q: reduce_key(target, q, QQ) for q in keys}
        rule_counts = Counter(rule for _, rule in reductions.values())
        checks.update({(target, q): result for q, (result, _) in reductions.items()})
        reduced, surviving = {}, 0
        for monomial, coefficient in terms:
            residual = []
            for q in monomial:
                result, _ = reductions[q]
                if result is None:
                    break
                factor, variable = result
                coefficient *= factor
                residual.append(variable)
            else:
                surviving += 1
                key = tuple(sorted(residual))
                reduced[key] = reduced.get(key, QQ(0)) + coefficient
        reduced = {m: c for m, c in reduced.items() if c}
        reduced_terms = [[m, [int(c.numerator()), int(c.denominator())]]
                         for m, c in sorted(reduced.items())]
        residual_keys = {q for m in reduced for q in m}
        cases.append({
            "target": target, "curve": case["curve"], "extra_markings": case["extra_markings"],
            "input_file": case["polynomial_file"], "input_sha256": case["polynomial_sha256"],
            "input_monomials": len(terms), "input_variables": len(keys),
            "rules_on_distinct_variables": dict(sorted(rule_counts.items())),
            "surviving_input_monomials": surviving, "reduced_monomials": len(reduced),
            "residual_ancestor_variables": sum(q[0] == "ancestor" for q in residual_keys),
            "residual_point_queries": sum(q[0] == "query" for q in residual_keys),
            "curve_unstable_point_queries": sum(q[0] == "query" and 2 * q[1] + len(q[3]) < 3
                                                for q in residual_keys),
            "reduced_terms": reduced_terms,
        })
    replay = lean_replay(checks)
    if replay_path is not None:
        replay_path.write_text(replay)
    return {
        "status": "exploration_passed",
        "environment": {"sage": version, "admcycles": "1.4",
                        "python": platform.python_version(), "architecture": platform.machine()},
        "source": str(SOURCE.relative_to(ROOT)), "source_sha256": SOURCE_SHA256,
        "script_sha256": digest(Path(__file__).read_bytes()),
        "rules": ["signed surface virtual dimension", "positive-class primary string",
                  "positive-class primary divisor with full signed intersections"],
        "format": "[monomial, [numerator, denominator]]; variables are "
                  "[ancestor or query, genus, full_curve, sorted [state_code, psi] pairs]",
        "cases": cases,
        "distinct_replay_checks": len(checks), "lean_replay_sha256": digest(replay.encode()),
        "nonclaims": ["The Lean file must actually be compiled before claiming kernel validation",
                      "Component replay does not certify the independent sparse graph expansion",
                      "No degree-zero geometric input or nonzero-power comparison is discharged",
                      "No numerical GW value, solved recurrence, or termination is asserted"],
    }


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, help="write the complete exploration report")
    parser.add_argument("--lean-replay", type=Path, help="emit all component checks for offline Lean replay")
    args = parser.parse_args()
    with tempfile.TemporaryDirectory(prefix="gw-surface-reduction-") as cache:
        os.environ["DOT_SAGE"] = cache
        os.environ["XDG_CACHE_HOME"] = cache
        report = json.dumps(explore(args.lean_replay), indent=2, sort_keys=True) + "\n"
        if args.output is None:
            print(report, end="")
        else:
            args.output.write_text(report)
