#!/usr/bin/env python3
"""Export stabilized primitive exceptional classes at four and five markings on both blowups."""
import argparse
import json
import os
from pathlib import Path
import tempfile
import textwrap

from export_admcycles_certificate import unique_object
from export_gkm_inputs import ROOT, producer_source, require
from gkm_plane_line_boundary_class import explore, lean_expression

REPORT = ROOT / "environments/gkm-exceptional-boundary-classes.json"
LEAN = ROOT / "AxiomaticGW/GKM/Fixtures/ExceptionalBoundaryData.lean"
CASES = [(1, 0), (2, 0), (2, 1)]


def vec(items):
    return "![" + ", ".join(items) + "]"


def render(cases):
    header = """/-
Copyright (c) 2026 JMA. All rights reserved.
Released under Apache 2.0 license as described in the file LICENSE.
Authors: JMA
-/
module

public import AxiomaticGW.GKM.EquivariantCoefficients
public import Mathlib.Data.Fin.VecNotation

/-!
# Original one-edge exceptional packets on the two blowups

Generated by `scripts/gkm_exceptional_boundary_classes.py`. State slots are
unit, hyperplane, first exceptional, second exceptional, point. The absent
second exceptional coordinate is padded with zero only on the first blowup.
-/

@[expose] public section
namespace AxiomaticGW.GKM.ExceptionalBoundaryData
open EquivariantCoefficients
noncomputable section

/-- The three distinct positive full classes in the held order. -/
inductive Case | f1 | first | second deriving DecidableEq, Repr

/-- Source factors of a fixed bridge, before either vertex integration. -/
structure Factors where
  /-- Localization contribution of the degree-one exceptional edge. -/
  edge : Coefficient
  /-- Tangent normalization from both incident vertices. -/
  tangent : Coefficient
  /-- Product of the ordered insertion restrictions at their marked point images. -/
  insertions : Coefficient
  /-- Product of the two target tangent weights at the left fixed point. -/
  eulerLeft : Coefficient
  /-- Product of the two target tangent weights at the right fixed point. -/
  eulerRight : Coefficient
  /-- Oriented flag weight from the left endpoint along the covered edge. -/
  flagLeft : Coefficient
  /-- Oriented flag weight from the right endpoint along the covered edge. -/
  flagRight : Coefficient
  /-- Automorphism denominator of the decorated fixed graph. -/
  automorphisms : Coefficient
  /-- Coefficient of the undecorated stabilized boundary stratum. -/
  boundary : Coefficient
  /-- Coefficient of the left node cotangent class when the new unit lies on the left. -/
  psiLeft : Coefficient
  /-- Coefficient of the right node cotangent class when the new unit lies on the right. -/
  psiRight : Coefficient
"""
    axes = ["f1", "first", "second"]
    expected = [["hirzebruchOne", [1, 0]], ["blowupTwo", [1, 0, 0]], ["blowupTwo", [0, 1, 0]]]
    pins = json.loads((ROOT / "environments/gkm-localization-source.json").read_text())
    require(len(cases) == 3, "Incomplete target set")
    parsed = []
    for report, (r, i), (target, curve) in zip(cases, CASES, expected):
        require(report["source"] == pins["revision"] and report["target"] == target and
                report["curve"] == curve and report["genus"] == 0 and report["unit_mark"] == 5 and
                report["sage"] == "10.9" and report["admcycles"] == "1.4" and
                report["normal_degree"] == -1 and report["common_refinement"] == [[1, 2], [5], [3, 4]]
                and [report["loci"][str(n)]["enumerated"] for n in (4, 5)] == [16, 32],
                "Changed source, curve, marking frame or fixed-locus count")
        base, = report["loci"]["4"]["nonzero_loci"]
        right, left = report["loci"]["5"]["nonzero_loci"]
        require([record["marks"] for record in (base, left, right)] == [
            [[1, 2], [3, 4]], [[1, 2, 5], [3, 4]], [[1, 2], [3, 4, 5]]],
            "Incorrect stabilized graph or cotangent branch")
        require(all(base[k] == left[k] == right[k] for k in base if k != "marks"),
                "Unequal shared bridge factors")
        fields = [base[k] for k in ("edge", "tangent", "insertions")] + base["eulers"] + base["flags"]
        fields += [str(base["automorphism"]), base["boundary"], left["node_psi"], right["node_psi"]]
        require(report["lifts"][:3] == [f"D{3+i}-D{3+i}(q)"] * 2 + [f"D{3+i}-D{3+i}(p)"]
                and report["lifts"][3] == ("D2" if i == 1 else "D1"), "Wrong toric insertions")

        def state_row(row):
            require(len(row) == r + 3, "Wrong number of node states")
            coeffs = list(map(str, row))
            if r == 1:
                coeffs.insert(3, "0")
            return vec([lean_expression(t).replace("x", "px").replace("y", "py") for t in coeffs])

        own = [int(j == i + 2) for j in range(r + 3)]
        fourth = [0, 1] + [(-1 if k == i or (r == 2 and i == 0) else 0) for k in range(r)] + [0]
        require(report["ordinary_insertions"] == [own] * 3 + [fourth] and
                report["tail_primary"] == [[-v for v in own], [0] * (r + 3)],
                "Changed ordinary insertion or three-point target state")
        graph_legs = [vec([str(next(j for j, group in enumerate(record["marks"]) if m in group))
                           for m in range(1, n + 1)])
                      for record, n in ((base, 4), (left, 5), (right, 5))]
        coordinates, tails = report["equivariant_insertions"], report["equivariant_tail"]
        require(len(coordinates) == 4 and len(tails) == 2, "Wrong insertion or tail arity")
        parsed.append(([lean_expression(t) for t in fields], list(map(state_row, coordinates)),
                       list(map(state_row, tails)), graph_legs))
    sections = [header, "/-- Original exact equivariant map and smoothing factors. -/",
                "def factors : Case → Factors"]
    for name, (values, _, _, _) in zip(axes, parsed):
        sections.append(f"  | .{name} => ⟨")
        for i, value in enumerate(values):
            sections.extend(textwrap.wrap("    " + value + ("," if i < len(values) - 1 else "⟩"),
                                         width=98, subsequent_indent="      ", break_long_words=False))
    for i, (name, n) in enumerate((("baseLeg", 4), ("leftLeg", 5), ("rightLeg", 5))):
        sections.extend(["", "/-- Stable endpoint carrying each ordered marking. -/",
                         f"def {name} : Case → Fin {n} → Fin 2"])
        sections.extend(f"  | .{axis} => {row[3][i]}" for axis, row in zip(axes, parsed))
    sections.extend(["", 'local notation "px" => (MvPolynomial.X (0 : Fin 2) : Polynomial)',
                     'local notation "py" => (MvPolynomial.X (1 : Fin 2) : Polynomial)'])
    for title, name, arity, index in (("Ordered insertion lifts", "lifts", 4, 1),
                                      ("Three-point tail with each node state", "tail", 2, 2)):
        sections.extend(["", f"/-- {title} in the ordinary surface basis over polynomial weights. -/",
                         f"def {name} : Case → Fin {arity} → Fin 5 → Polynomial"])
        for axis, row in zip(axes, parsed):
            sections.append(f"  | .{axis} => ![")
            sections.extend("    " + value + ("," if i < arity - 1 else "]")
                            for i, value in enumerate(row[index]))
    return "\n".join(sections + ["", "end", "end AxiomaticGW.GKM.ExceptionalBoundaryData", ""])


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    group = parser.add_mutually_exclusive_group(required=True)
    group.add_argument("--producer", type=Path)
    group.add_argument("--replay", type=Path)
    parser.add_argument("--output", type=Path, default=REPORT)
    parser.add_argument("--lean-output", type=Path, default=LEAN)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    if args.replay:
        data = json.loads(args.replay.read_text(), object_pairs_hook=unique_object)
    else:
        producer, pin = producer_source(args.producer)
        with tempfile.TemporaryDirectory(prefix="gkm-exceptional-classes-") as temporary:
            for name in ("DOT_SAGE", "ADMCYCLES_CACHE_DIR", "MPLCONFIGDIR", "XDG_CACHE_HOME"):
                path = Path(temporary) / name
                path.mkdir()
                os.environ[name] = str(path)
            (Path(os.environ["DOT_SAGE"]) / "admcycles").mkdir()
            data = [explore(producer, pin, blowups=r, exceptional=i) for r, i in CASES]
    lean = render(data)
    if not args.replay:
        packet = json.dumps(data, indent=2, sort_keys=True) + "\n"
        if args.check:
            require(args.output.read_text() == packet, "Held native packets differ")
        else:
            args.output.write_text(packet)
    if args.check:
        require(args.lean_output.read_text() == lean, "Held Lean packets differ")
    else:
        args.lean_output.write_text(lean)


if __name__ == "__main__":
    main()
