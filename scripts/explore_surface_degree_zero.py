#!/usr/bin/env python3
"""Explore degree-zero substitution and emit checked exact collection identities.

Input is the pinned previous primary-reduction report. The Lean replay checks
each constant/retained variable and the complete rational collection for all
assignments of residual variables. It does not certify the earlier independent
raw graph expansion or discharge geometric input and seed hypotheses.
"""

import argparse
import hashlib
import importlib.metadata
import json
import os
from pathlib import Path
import platform
import sys
import tempfile

sys.dont_write_bytecode = True
from explore_surface_reduction import TARGETS, lean_vector


ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "environments/surface-primary-reduction-exploration.json"
SOURCE_SHA256 = "f859e67febe1608b1b2897123a86a2c704c4ac2c891c9311cc8e1007b01b0048"


def digest(data):
    return hashlib.sha256(data).hexdigest()


def variable(raw):
    tag, genus, curve, insertions = raw
    return tag, genus, tuple(curve), tuple(tuple(s) for s in insertions)


def constant_value(v, QQ):
    tag, genus, curve, insertions = v
    if tag != "ancestor" or any(curve) or any(psi for _, psi in insertions):
        return None
    labels = sorted(label for label, _ in insertions)
    if genus == 0:
        if labels in ([0, 0, 2], [0, 1, 1]):
            return QQ(1)
        if len(labels) == 3 and labels[0] == 0 and labels[1] == labels[2] and labels[1] >= 3:
            return QQ(-1)
        return QQ(0)
    if genus == 1:
        if labels == [1]:
            return -QQ(1) / 8
        if len(labels) == 1 and labels[0] >= 3:
            return -QQ(1) / 24
        return QQ(0)
    return None


def lean_rational(c):
    return f"({c.numerator()} / {c.denominator()} : ℚ)"


def lean_variable(target, v):
    tag, genus, curve, insertions = v
    lean_target = "." + TARGETS[target][0]
    labels = [".unit", ".hyperplane", ".point"]
    entries = ", ".join(f"⟨{labels[a] if a < 3 else f'.exceptional {a - 3}'}, {psi}⟩"
                        for a, psi in insertions)
    if tag == "ancestor":
        return (f".inl ⟨{genus}, {lean_vector(curve)}, "
                f"(↑([{entries}] : List (SurfaceInsertion {lean_target})) : "
                f"Multiset (SurfaceInsertion {lean_target})), by decide +kernel⟩")
    if tag == "query":
        return f".inr ⟨{genus}, {lean_vector(curve)}, [{entries}]⟩"
    raise ValueError(f"Unknown variable tag: {tag}")


def lean_replay(checks, cases):
    lines = ["-- Generated by scripts/explore_surface_degree_zero.py.",
             "-- Constants and collection only; raw graph expansion and geometry remain separate.",
             "module", "import AxiomaticGW.Surfaces.DegreeZeroPolynomial", "",
             "set_option linter.privateModule false", "",
             "open AxiomaticGW SurfacePolynomialReduction", ""]
    names = {key: f"v{i:04d}" for i, key in enumerate(sorted(checks))}
    proofs = {key: f"step{i:04d}" for i, key in enumerate(sorted(checks))}
    for (target, v), result in sorted(checks.items()):
        name, proof = names[target, v], proofs[target, v]
        expected = "none" if result is None else f"some {lean_rational(result)}"
        lines.append(f"private def {name} : Variable .{TARGETS[target][0]} := {lean_variable(target, v)}")
        lines.append(f"private theorem {proof} : degreeZeroValue? {name} = {expected} := by decide +kernel\n")
    for case in cases:
        target = case["target"]
        def expression(terms, reduce):
            output = []
            for monomial, coefficient in terms:
                factors = [lean_rational(coefficient)]
                for v in monomial:
                    name = names[target, v]
                    factors.append(f"(MvPolynomial.aeval value (degreeZeroPolynomial {name}))" if reduce
                                   else f"(value {name})")
                output.append(" * ".join(factors))
            return " +\n      ".join(output) if output else "0"
        steps = ", ".join(proofs[target, v] for v in sorted(case["variables"]))
        lines.append(f"-- {target}, curve {case['curve']}, extra markings {case['extra_markings']}")
        lines.append(f"example (value : Variable .{TARGETS[target][0]} → ℚ) :\n"
                     f"    {expression(case['input_terms'], True)} =\n"
                     f"    {expression(case['output_terms'], False)} := by\n"
                     f"  simp only [degreeZeroPolynomial, {steps},\n"
                     f"    MvPolynomial.aeval_C, Algebra.algebraMap_self, RingHom.id_apply,\n"
                     f"    MvPolynomial.aeval_X]\n"
                     f"  ring\n")
    return "\n".join(lines)


def explore(replay_path=None):
    from sage.all import QQ
    from sage.version import version

    if version != "10.9" or importlib.metadata.version("admcycles") != "1.4":
        raise RuntimeError("Review the pinned Sage/admcycles environment")
    data = SOURCE.read_bytes()
    if digest(data) != SOURCE_SHA256:
        raise RuntimeError("The pinned primary-reduction report changed")
    source = json.loads(data)
    dependency = ROOT / "scripts/explore_surface_reduction.py"
    if digest(dependency.read_bytes()) != source["script_sha256"]:
        raise RuntimeError("The imported target/coordinate helper changed")
    cases, work, checks = [], [], {}
    for case in source["cases"]:
        target = case["target"]
        terms = [(tuple(variable(v) for v in monomial), QQ(c[0]) / c[1])
                 for monomial, c in case["reduced_terms"]]
        variables = {v for m, _ in terms for v in m}
        constants = {v: constant_value(v, QQ) for v in variables}
        checks.update({(target, v): value for v, value in constants.items()})
        collected = {}
        for monomial, coefficient in terms:
            residual = []
            for v in monomial:
                if constants[v] is None:
                    residual.append(v)
                else:
                    coefficient *= constants[v]
            key = tuple(sorted(residual))
            collected[key] = collected.get(key, QQ(0)) + coefficient
        output = sorted((m, c) for m, c in collected.items() if c)
        beta = tuple(case["curve"])
        energy = sum(w * b for w, b in zip(TARGETS[target][1], beta))
        leading = (("query", 1, beta, ((2, 0),) * energy),)
        if collected.get(leading) != -9:
            raise RuntimeError("Unexpected elliptic leading coefficient")
        if any(v[0] != "query" for m, _ in output for v in m):
            raise RuntimeError("An unhandled ancestor remains in this primary example")
        cases.append({"target": target, "curve": case["curve"],
                      "extra_markings": case["extra_markings"], "input_monomials": len(terms),
                      "output_monomials": len(output), "input_variables": len(variables),
                      "constant_variables": sum(c is not None for c in constants.values()),
                      "residual_point_queries": len({v for m, _ in output for v in m}),
                      "leading_variable": leading[0], "leading_coefficient": [-9, 1],
                      "terms": [[m, [int(c.numerator()), int(c.denominator())]] for m, c in output]})
        work.append({"target": target, "curve": case["curve"], "extra_markings": case["extra_markings"],
                     "variables": variables, "input_terms": terms, "output_terms": output})
    replay = lean_replay(checks, work)
    if replay_path is not None:
        replay_path.write_text(replay)
    return {"status": "exploration_passed", "environment": {
                "sage": version, "admcycles": "1.4", "python": platform.python_version(),
                "architecture": platform.machine()},
            "source": str(SOURCE.relative_to(ROOT)), "source_sha256": SOURCE_SHA256,
            "script_sha256": digest(Path(__file__).read_bytes()),
            "helper_sha256": source["script_sha256"], "cases": cases,
            "distinct_component_checks": len(checks), "symbolic_collection_checks": len(cases),
            "lean_replay_sha256": digest(replay.encode()),
            "nonclaims": ["The generated Lean file must be compiled to establish its checks",
                          "The earlier raw sparse graph expansion is not certified by this replay",
                          "Geometric laws and elliptic seed equalities remain explicit inputs",
                          "The four leading coefficients do not prove a uniform recurrence or termination",
                          "No numerical GW value is proved by this exploration alone"]}


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path)
    parser.add_argument("--lean-replay", type=Path)
    args = parser.parse_args()
    with tempfile.TemporaryDirectory(prefix="gw-degree-zero-") as cache:
        os.environ["DOT_SAGE"] = cache
        os.environ["XDG_CACHE_HOME"] = cache
        report = json.dumps(explore(args.lean_replay), indent=2, sort_keys=True) + "\n"
        if args.output is None:
            print(report, end="")
        else:
            args.output.write_text(report)
